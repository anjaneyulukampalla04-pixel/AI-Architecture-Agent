@router.post("/{id}/architecture/modify")
async def modify_project_architecture_with_ai(
    id: str,
    payload: ArchitectureModifyRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Convert a natural-language architecture command into a real,
    persisted architectureData modification.

    Examples:
      - Add Redis cache between API Server and Database
      - Add AWS S3 bucket for uploaded files
      - Add GET /api/v1/analytics endpoint
      - Rename table users to accounts
      - Remove Message Queue
      - Add NotificationService
    """
    instruction = payload.instruction.strip()

    if not instruction:
        raise HTTPException(
            status_code=400,
            detail="Modification instruction cannot be empty.",
        )

    # Verify ownership.
    project_result = await db.execute(
        select(Project).filter(
            Project.id == id,
            Project.ownerId == current_user.id,
        )
    )

    project = project_result.scalars().first()

    if not project:
        raise HTTPException(
            status_code=404,
            detail="Project not found",
        )

    # Load latest architecture.
    version_result = await db.execute(
        select(ArchitectureVersion)
        .filter(ArchitectureVersion.projectId == id)
        .order_by(ArchitectureVersion.versionNumber.desc())
    )

    latest_version = version_result.scalars().first()

    if (
        not latest_version
        or not latest_version.architectureData
    ):
        raise HTTPException(
            status_code=404,
            detail="No architecture has been generated yet.",
        )

    try:
        if isinstance(latest_version.architectureData, dict):
            # Deep-copy through JSON so we never accidentally mutate
            # SQLAlchemy's existing JSON object before validation.
            current_architecture = json.loads(
                json.dumps(latest_version.architectureData)
            )
        else:
            current_architecture = json.loads(
                latest_version.architectureData
            )

        current_architecture = _normalise_architecture(
            current_architecture
        )
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Current architecture data is invalid: {str(exc)}",
        )

    system_prompt = """
You are an AI software architecture modification engine.

Your task is to MODIFY the supplied architecture JSON according to the
user's instruction. Do not merely explain what the user could do.

Return ONLY valid JSON. Do not return Markdown and do not wrap the
response in ```json fences.

Return exactly this outer structure:

{
  "message": "Short description of what changed",
  "architectureData": {
    "...": "the COMPLETE modified architecture"
  }
}

Rules:

1. Preserve every unrelated part of the existing architecture.
2. architectureData must contain the COMPLETE architecture, not only
   the changed item.
3. Preserve unknown top-level fields. Do not discard fields simply
   because they are not listed in this prompt.
4. Keep components, database_schema, apis, cloud_mappings, costs and
   documentation when they already exist.
5. Never delete an unrelated component, API, table, mapping or field.

COMPONENTS
- When adding a component, follow the shape already used by existing
  components whenever possible.
- A new component should normally have id, name, type and description.
- Use a stable unique string id.
- Suitable types include Microservice, Cache, Object Storage, Database,
  Queue, API Server, Load Balancer, Authentication Service, Worker,
  Gateway and External Service.
- If the user asks for Redis, create a Redis/Cache component.
- If the user asks for AWS S3, create an AWS S3/Object Storage component.
- If the user asks for a named service, preserve that service name.

APIS
- API entries should preserve the existing API object shape.
- At minimum a newly added API should contain:
  method, path, description
- Common methods are GET, POST, PUT, PATCH and DELETE.
- Do not create a duplicate with the same method and path.

DATABASE
- Preserve the existing table and column shapes.
- When renaming a table, preserve its columns and other properties.
- Do not remove unrelated tables.
- When adding a table, use the existing column conventions where possible.

CLOUD MAPPINGS
- If the architecture already has cloud_mappings and the user explicitly
  adds an AWS/cloud resource, add an appropriate mapping when useful.
- Preserve all existing mappings.

CONNECTIONS
- If architectureData already contains a connections array, preserve it
  and update it when the instruction clearly describes a relationship.
- A connection should follow the existing connection shape. If the
  existing shape is { "from": "...", "to": "..." }, continue using it.
- Do not replace an existing connection representation with a new schema.

REMOVE
- If the user explicitly asks to remove an element, remove only that
  requested element and directly related connections.

RENAME
- Preserve all properties and change only the requested name/identifier
  unless another change is necessary to keep references consistent.

The message must be concise, for example:
"Added Redis Cache between API Server and Database."
"""

    user_prompt = (
        "CURRENT ARCHITECTURE:\n\n"
        + json.dumps(
            current_architecture,
            indent=2,
            ensure_ascii=False,
        )
        + "\n\nUSER MODIFICATION:\n\n"
        + instruction
        + "\n\nReturn the required JSON object only."
    )

    provider = os.getenv(
        "LLM_PROVIDER",
        "groq",
    ).lower().strip()

    raw_response = None

    try:
        raw_response = await _call_architecture_llm(
            provider,
            system_prompt,
            user_prompt,
        )
    except Exception as primary_error:
        print(
            "[ARCH MODIFY] Primary provider failed:",
            repr(primary_error),
        )

        # Same fallback strategy used by the chat route.
        if provider == "groq":
            try:
                raw_response = await _call_architecture_llm(
                    "gemini",
                    system_prompt,
                    user_prompt,
                )
            except Exception as fallback_error:
                print(
                    "[ARCH MODIFY] Gemini fallback failed:",
                    repr(fallback_error),
                )
                raise HTTPException(
                    status_code=503,
                    detail=(
                        "AI architecture modification service "
                        "is currently unavailable."
                    ),
                )
        else:
            raise HTTPException(
                status_code=503,
                detail=(
                    "AI architecture modification service "
                    "is currently unavailable."
                ),
            )

    try:
        parsed = _extract_json_object(raw_response)

        if "architectureData" not in parsed:
            raise ValueError(
                "architectureData missing from AI response"
            )

        modified_architecture = _normalise_architecture(
            parsed["architectureData"]
        )

        message = str(
            parsed.get(
                "message",
                "Architecture updated successfully.",
            )
        ).strip()

        if not message:
            message = "Architecture updated successfully."

    except Exception as parse_error:
        print(
            "[ARCH MODIFY] Invalid LLM response:",
            raw_response,
        )
        print(
            "[ARCH MODIFY] Parse error:",
            repr(parse_error),
        )

        raise HTTPException(
            status_code=500,
            detail=(
                "AI returned an invalid architecture modification."
            ),
        )

    # Persist immediately. The frontend can therefore redraw from the
    # returned data without requiring a second Save click.
    latest_version.architectureData = modified_architecture

    try:
        await db.commit()
        await db.refresh(latest_version)
    except Exception as db_error:
        await db.rollback()

        print(
            "[ARCH MODIFY] Database save failed:",
            repr(db_error),
        )

        raise HTTPException(
            status_code=500,
            detail="Failed to save modified architecture.",
        )

    return {
        "status": "success",
        "message": message,
        "architectureData": modified_architecture,
        "versionNumber": latest_version.versionNumber,
    }


