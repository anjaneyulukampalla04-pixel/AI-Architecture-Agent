def _get_architecture_llm_client(provider: str):
    """
    Create an OpenAI-compatible client for Groq or Gemini.

    This uses the same environment variable names as chat.py:
      GROQ_API_KEYS
      GROQ_BASE_URL
      GROQ_MODEL
      GEMINI_API_KEYS
      GEMINI_BASE_URL
      GEMINI_MODEL
    """
    provider = provider.lower().strip()

    if provider == "groq":
        api_key = os.getenv("GROQ_API_KEYS", "").split(",")[0].strip()

        if not api_key:
            raise RuntimeError("GROQ_API_KEYS is missing")

        return (
            AsyncOpenAI(
                api_key=api_key,
                base_url=os.getenv(
                    "GROQ_BASE_URL",
                    "https://api.groq.com/openai/v1",
                ),
            ),
            os.getenv(
                "GROQ_MODEL",
                "llama-3.3-70b-versatile",
            ),
        )

    if provider == "gemini":
        api_key = os.getenv("GEMINI_API_KEYS", "").split(",")[0].strip()

        if not api_key:
            raise RuntimeError("GEMINI_API_KEYS is missing")

        return (
            AsyncOpenAI(
                api_key=api_key,
                base_url=os.getenv(
                    "GEMINI_BASE_URL",
                    "https://generativelanguage.googleapis.com/v1beta/openai",
                ),
            ),
            os.getenv(
                "GEMINI_MODEL",
                "gemini-2.5-flash",
            ),
        )

    raise RuntimeError(f"Unsupported LLM provider: {provider}")


def _extract_json_object(text: str) -> Dict[str, Any]:
    """
    Parse the JSON returned by the LLM.

    It also tolerates accidental ```json ... ``` wrappers even though
    the prompt explicitly tells the model not to use Markdown fences.
    """
    if not text or not text.strip():
        raise ValueError("AI returned an empty response")

    cleaned = text.strip()

    cleaned = re.sub(
        r"^```(?:json)?\s*",
        "",
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(r"\s*```$", "", cleaned)

    try:
        parsed = json.loads(cleaned)
    except json.JSONDecodeError:
        start = cleaned.find("{")
        end = cleaned.rfind("}")

        if start == -1 or end == -1 or end <= start:
            raise ValueError("AI did not return valid JSON")

        parsed = json.loads(cleaned[start:end + 1])

    if not isinstance(parsed, dict):
        raise ValueError("AI response must be a JSON object")

    return parsed


def _normalise_architecture(data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Keep the architecture shape predictable for the frontend while
    preserving extra fields generated by the agent pipeline.
    """
    if not isinstance(data, dict):
        raise ValueError("architectureData must be a JSON object")

    data.setdefault("components", [])
    data.setdefault("database_schema", [])
    data.setdefault("apis", [])
    data.setdefault("cloud_mappings", [])
    data.setdefault("costs", {})

    if not isinstance(data["components"], list):
        data["components"] = []

    if not isinstance(data["database_schema"], list):
        data["database_schema"] = []

    if not isinstance(data["apis"], list):
        data["apis"] = []

    if not isinstance(data["cloud_mappings"], list):
        data["cloud_mappings"] = []

    if not isinstance(data["costs"], dict):
        data["costs"] = {}

    return data


async def _call_architecture_llm(
    provider: str,
    system_prompt: str,
    user_prompt: str,
) -> str:
    client, model = _get_architecture_llm_client(provider)

    response = await client.chat.completions.create(
        model=model,
        messages=[
            {
                "role": "system",
                "content": system_prompt,
            },
            {
                "role": "user",
                "content": user_prompt,
            },
        ],
        temperature=0.1,
        max_tokens=6000,
    )

    if (
        not response.choices
        or not response.choices[0].message.content
    ):
        raise RuntimeError("LLM returned an empty response")

    return response.choices[0].message.content


